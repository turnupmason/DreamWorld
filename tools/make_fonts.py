# Builds the game's web fonts: subsets of Resource Han Rounded SC (Chinese) and Nunito (Latin, numbers).
# game  = every CJK character the game's own text uses (always loaded, small)
# common = the 3,755 most common Chinese characters minus those (loaded only when a page shows one, e.g. a typed name)
import glob, os, re, subprocess, sys

# Usage: put the source fonts in tools/font-src/ (not in git, see prototype/fonts/FONTS-LICENSE.md for where to get them):
#   tools/font-src/Nunito.ttf                                         (google/fonts: ofl/nunito/Nunito[wght].ttf)
#   tools/font-src/rhr/ResourceHanRoundedCN-Medium.ttf and -Bold.ttf  (CyanoHao/Resource-Han-Rounded, release RHR-CN)
# then: python -m pip install fonttools brotli ; python tools/make_fonts.py
# Run it again whenever the game gets new Chinese text, so the new characters land in the small font.
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SP = os.path.join(ROOT, 'tools')
DL = os.path.join(SP, 'font-src')
OUT = os.path.join(ROOT, 'prototype', 'fonts')
SRC = os.path.join(ROOT, 'prototype')
os.makedirs(OUT, exist_ok=True)

text = ''
for f in glob.glob(os.path.join(SRC, 'js', '*.js')) + [os.path.join(SRC, 'index.html')]:
    text += open(f, encoding='utf-8').read()
cjk = lambda c: '\u3000' <= c <= '\u9fff' or '\uff00' <= c <= '\uffef'
game = sorted(set(c for c in text if cjk(c)))
punct = '，。！？、：；“”‘’（）《》〈〉【】·—…～「」『』％＋－×÷°'
game = sorted(set(game) | set(punct))

common = []
for hi in range(0xB0, 0xD8):
    for lo in range(0xA1, 0xFF):
        try:
            c = bytes([hi, lo]).decode('gb2312')
            common.append(c)
        except UnicodeDecodeError:
            pass
common = sorted(set(common) - set(game))
print('game chars', len(game), 'common chars', len(common))

def ranges(chars):
    cps = sorted(ord(c) for c in chars)
    out, start, prev = [], cps[0], cps[0]
    for cp in cps[1:]:
        if cp == prev + 1:
            prev = cp; continue
        out.append((start, prev)); start = prev = cp
    out.append((start, prev))
    return ','.join(f'U+{a:X}' if a == b else f'U+{a:X}-{b:X}' for a, b in out)

def subset(src, out, chars=None, unicodes=None):
    args = [sys.executable, '-I', '-m', 'fontTools.subset', src, '--flavor=woff2', '--output-file=' + out,
            '--layout-features=*', '--no-hinting', '--desubroutinize', '--name-IDs=*']
    if chars is not None:
        tf = out + '.txt'
        open(tf, 'w', encoding='utf-8').write(''.join(chars))
        args.append('--text-file=' + tf)
    if unicodes:
        args.append('--unicodes=' + unicodes)
    subprocess.run(args, check=True)
    if chars is not None:
        os.remove(tf)
    print(os.path.basename(out), os.path.getsize(out) // 1024, 'KB')

for w in ['Medium', 'Bold']:
    src = os.path.join(DL, 'rhr', f'ResourceHanRoundedCN-{w}.ttf')
    subset(src, os.path.join(OUT, f'round-{w.lower()}-game.woff2'), game)
    subset(src, os.path.join(OUT, f'round-{w.lower()}-common.woff2'), common)
subset(os.path.join(DL, 'Nunito.ttf'), os.path.join(OUT, 'nunito.woff2'), unicodes='U+0020-007E,U+00A0-00FF,U+2013-2014,U+2018-201E,U+2022,U+2026,U+20AC,U+2122,U+00B0,U+00D7')


# OFL: a modified font may not use the Reserved Font Name ('Source'), so the subsets get our own name.
from fontTools.ttLib import TTFont
for w, wt in [('medium', 'Medium'), ('bold', 'Bold')]:
    for part in ['game', 'common']:
        p = os.path.join(OUT, f'round-{w}-{part}.woff2')
        f = TTFont(p)
        for rec in f['name'].names:
            if rec.nameID in (1, 16):
                rec.string = 'MirrorTown Round'
            elif rec.nameID in (2, 17):
                rec.string = wt
            elif rec.nameID in (3, 4):
                rec.string = 'MirrorTown Round ' + wt
            elif rec.nameID == 6:
                rec.string = 'MirrorTownRound-' + wt
        f.flavor = 'woff2'
        f.save(p)
print('renamed')

# fonts.css: Nunito for Latin and numbers; MirrorTown Round for Chinese. The "common" files have a unicode-range,
# so the browser only downloads them when a page shows one of those characters (a name or a letter someone typed).
g, c = ranges(game), ranges(common)
css = ['/* Generated by tools/make_fonts.py — do not edit by hand. Licenses: fonts/FONTS-LICENSE.md */',
       "@font-face { font-family: 'MT Nunito'; src: url(nunito.woff2) format('woff2'); font-weight: 200 1000; font-display: swap; }"]
for w, rng in [('medium', '100 599'), ('bold', '600 1000')]:
    css.append(f"@font-face {{ font-family: 'MT Round'; src: url(round-{w}-game.woff2) format('woff2'); font-weight: {rng}; font-display: swap; unicode-range: {g}; }}")
    css.append(f"@font-face {{ font-family: 'MT Round'; src: url(round-{w}-common.woff2) format('woff2'); font-weight: {rng}; font-display: swap; unicode-range: {c}; }}")
open(os.path.join(OUT, 'fonts.css'), 'w', encoding='utf-8').write('\n'.join(css) + '\n')
print('fonts.css written')
